lst = [29, 10, 14, 37, 13]  # Исходный неотсортированный список 
n = len(lst)  # Длина списка
for i in range(n - 1):   # Внешний цикл идем по местам в списке от 0 до предпоследнего
    min_idx = i  # Заводим переменную для индекса минимума 
    for j in range(i + 1, n):  # Внутренний цикл: ищем элемент еще меньше в оставшейся части
        if lst[j] < lst[min_idx]: # Если нашли число меньше нашего текущего минимума:
            min_idx = j  # Обновляем сохраненный индекс минимального элемента
    lst[i], lst[min_idx] = lst[min_idx], lst[i] # Меняем местами текущий элемент и найденный минимум
    print(lst) # Выводим текущее состояние списка после каждого прохода

