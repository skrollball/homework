numbers = [2, 5, 8, 11, 14, 18, 21, 25, 30] # Исходный отсортированный список
a = 18 # Искомое число
left = 0 # Левая граница поиска (индекс начала)
right = len(numbers) - 1 # Правая граница поиска (индекс конца)
b = -1 # Ответ по умолчанию (если не найдем)
while left <= right: # Цикл работает, пока границы не пересекутся
    mid = (left + right) //2 # Находим индекс середины отрезка
    if numbers[mid] == a: # Если число в середине — это наша цель
        b = mid # Запоминаем индекс
        break # Останавливаем цикл
    elif numbers[mid] < a: # Если середина меньше цели:
        left = mid + 1 # Сдвигаем левую границу вправо
    else: # Если середина больше цели:
        right = mid - 1# Сдвигаем правую границу влево
print(b) # Выводим финальный индекс (в данном случае 5)
