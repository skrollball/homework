def merge_sort(lst): # Функция для разделения списка
    if len(lst) <= 1: # Если в списке 1 элемент или меньше:
        return lst # Он уже отсортирован, возвращаем его
    mid = len(lst) // 2 # Находим индекс середины списка
    left = merge_sort(lst[:mid]) # Рекурсивно сортируем левую половину
    right = merge_sort(lst[mid:]) # Рекурсивно сортируем правую половину
    return merge(left, right) # Сливаем две отсортированные половины
def merge(left, right): # Функция для слияния двух списков в один
    res = [] # Сюда будем собирать упорядоченные числа
    i = j = 0 # Указатели (индексы) для левого и правого списков
    while i < len(left) and j < len(right): # Пока в обоих списках есть элементы:
        if left[i] < right[j]: # Если левый элемент меньше правого:
            res.append(left[i]) # Добавляем левый в результат
            i += 1 # Сдвигаем указатель левого списка
        else: # Если правый элемент меньше или равен левому:
            res.append(right[j]) # Добавляем правый в результат
            j += 1 # Сдвигаем указатель правого списка
    res.extend(left[i:]) # Добавляем оставшиеся элементы из левого списка
    res.extend(right[j:]) # Добавляем оставшиеся элементы из правого списка
    return res # Возвращаем объединенный отсортированный список
sourcelst = [12, 4, 9, 1, 6, 3] # Создаем исходный неотсортированный список
sortedlst = merge_sort(sourcelst) # Запускаем сортировку и сохраняем в новую переменную
print("Исходный:", sourcelst) # Выводим начальное состояние списка (теперь покажет оригинал)
print("Полученный:", sortedlst) # Выводим итоговый отсортированный список